const FONT_H = 9, LINE_H = 10, SPACE_W = 3;
const glyphW = new Uint8Array(128), glyphBits = [];
(function buildFont() {
  for (let c = 0; c < 128; c++) glyphBits[c] = null;
  for (const ch in FONT_SRC) {
    const rows = FONT_SRC[ch].split('|'), w = rows[0].length, bits = new Uint8Array(w * FONT_H);
    for (let r = 0; r < rows.length; r++) for (let x = 0; x < w; x++) if (rows[r][x] === '#') bits[r * w + x] = 1;
    glyphW[ch.charCodeAt(0)] = w; glyphBits[ch.charCodeAt(0)] = bits;
  }
})();
function charW(code) { return code === 32 ? SPACE_W : (glyphBits[code] ? glyphW[code] : 4); }
function textWidth(s) {
  let w = 0;
  for (let i = 0; i < s.length; i++) w += charW(s.charCodeAt(i)) + 1;
  return w > 0 ? w - 1 : 0;
}
function drawChar(code, x, y, c) {
  const bits = glyphBits[code]; if (!bits) return;
  const w = glyphW[code];
  for (let r = 0; r < FONT_H; r++) for (let i = 0; i < w; i++) if (bits[r * w + i]) pset(x + i, y + r, c);
}
// plain text
function drawText(s, x, y, c) {
  for (let i = 0; i < s.length; i++) { const k = s.charCodeAt(i); drawChar(k, x, y, c); x += charW(k) + 1; }
  return x;
}
// text with a 1px dark outline (legible over any background)
function drawTextOutlined(s, x, y, c, oc) {
  if (oc === undefined) oc = C.BLK;
  for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) if (dx || dy) drawText(s, x + dx, y + dy, oc);
  drawText(s, x, y, c);
}
function drawTextShadow(s, x, y, c, sc) { drawText(s, x + 1, y + 1, sc === undefined ? C.BLK : sc); drawText(s, x, y, c); }
// greedy word wrap -> array of lines
function wrapText(s, maxW) {
  const out = [], paras = s.split('\n');
  for (const p of paras) {
    const words = p.split(' ');
    let line = '';
    for (const w of words) {
      const test = line ? line + ' ' + w : w;
      if (textWidth(test) <= maxW || !line) line = test;
      else { out.push(line); line = w; }
    }
    out.push(line);
  }
  return out;
}
